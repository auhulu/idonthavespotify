import { afterEach, describe, expect, it, spyOn } from 'bun:test';

import { MetadataType } from '~/config/enum';
import { getYouTubeMetadata, getYouTubeQueryFromMetadata } from '~/parsers/youtube';
import { cacheStore } from '~/services/cache';
import HttpClient from '~/utils/http-client';
import { getServiceGuard } from '~/utils/service-guard';

const query = (title: string, description = '', type = MetadataType.Song) =>
  getYouTubeQueryFromMetadata({ title, description, type });

describe('YouTube search query', () => {
  it('ignores production credits and lyrics in official video descriptions', () => {
    expect(
      query(
        'The Weeknd - Blinding Lights (Official Video)',
        'Camera & Lighting: A Person\nProduction · Another Person\nLyrics:\nExample lyric text'
      )
    ).toBe('The Weeknd - Blinding Lights');
  });

  it('ignores promotional links and other songs mentioned after an ampersand', () => {
    expect(
      query(
        'Ed Sheeran - Shape of You [Official Music Video]',
        'Listen to Shape of You & another song.\nSubscribe: https://example.com'
      )
    ).toBe('Ed Sheeran - Shape of You');
  });

  it('cleans titles already cached without brackets', () => {
    expect(
      query('The Weeknd Blinding Lights Official Video', 'Credits & Someone\nLyrics')
    ).toBe('The Weeknd Blinding Lights');
  });

  it('keeps featured artists after the video label', () => {
    expect(
      query('Daft Punk - Get Lucky (Official Audio) ft. Pharrell Williams, Nile Rodgers')
    ).toBe('Daft Punk - Get Lucky ft. Pharrell Williams, Nile Rodgers');
  });

  it('uses only the matching song line in distributor-generated descriptions', () => {
    expect(
      query(
        'Blinding Lights',
        'Provided to YouTube by Universal Music Group\r\n\r\nBlinding Lights · The Weeknd\r\n\r\nAfter Hours\r\n℗ 2020\r\nProducer · Someone\r\nAuto-generated by YouTube.'
      )
    ).toBe('Blinding Lights The Weeknd');
  });

  it('preserves ampersands in a structured artist name', () => {
    expect(
      query('Song', 'Provided to YouTube by Label\n\nSong · Simon & Garfunkel\n\nCredits')
    ).toBe('Song Simon & Garfunkel');
  });

  it('does not scan later credits if the first metadata line does not match', () => {
    expect(
      query(
        'Song',
        'Provided to YouTube by Label\n\nOther Song · Wrong Artist\nSong · Producer'
      )
    ).toBe('Song');
  });

  it('preserves Unicode, song subtitles, and recording versions', () => {
    expect(query('米津玄師 - Lemon (Live) [Official Video]')).toBe(
      '米津玄師 - Lemon (Live)'
    );
    expect(query('Beyoncé - Song (Remix)')).toBe('Beyoncé - Song (Remix)');
    expect(query('Song (Part 2)')).toBe('Song (Part 2)');
  });

  it('handles empty descriptions and preserves collection suffixes', () => {
    expect(query('Adele - Rolling in the Deep (Official Music Video)')).toBe(
      'Adele - Rolling in the Deep'
    );
    expect(query('Album', '', MetadataType.Album)).toBe('Album album');
    expect(query('Mix', '', MetadataType.Playlist)).toBe('Mix playlist');
  });
});

describe('YouTube metadata to query', () => {
  afterEach(() => cacheStore.reset());

  it('preserves title boundaries and Unicode through metadata extraction', async () => {
    // Other suites intentionally open the shared circuit with upstream errors.
    const guard = spyOn(getServiceGuard('youTube'), 'acquire').mockReturnValue(true);
    const mock = spyOn(HttpClient, 'get').mockResolvedValue({
      items: [
        {
          snippet: {
            title: '米津玄師 - Lemon (Live) [Official Video]',
            description: 'Director & Editor: Someone\nLyrics: example',
            thumbnails: {},
          },
        },
      ],
    });
    try {
      cacheStore.reset();
      const metadata = await getYouTubeMetadata(
        'testvideo01',
        'https://www.youtube.com/watch?v=testvideo01'
      );
      expect(metadata.title).toBe('米津玄師 - Lemon (Live) [Official Video]');
      expect(getYouTubeQueryFromMetadata(metadata)).toBe('米津玄師 - Lemon (Live)');
    } finally {
      mock.mockRestore();
      guard.mockRestore();
    }
  });
});
